BY_CODE: dict[str, Country] = {c["code"]: c for c in COUNTRIES}
DEFAULT_COUNTRY = "UG"


def country(code: str | None) -> Country | None:
    return BY_CODE.get((code or "").upper())


def phone_prefix(code: str | None) -> str:
    c = country(code)
    return c["phone_prefix"] if c else BY_CODE[DEFAULT_COUNTRY]["phone_prefix"]


def validate_region(code: str, region: str) -> str | None:
    """Error message if ``region`` is not an area of a supported ``code``; None if fine."""
    c = country(code)
    if c is None or not region:
        return None
    if region not in c["regions"]:
        return f"Choose a {c['region_label'].lower()} of {c['name']}."
    return None


def locale_for(code: str) -> dict[str, Any]:
    c = country(code)
    return {"currency": c["currency"], "timezone": c["timezone"]} if c else {}
